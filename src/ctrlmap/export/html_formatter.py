def _render_framework_gap_tab(
    results: list[MappedResult],
    fw_results: dict[str, list[MappedResult]],
    is_multi: bool,
) -> str:
    """Build the content for the Framework Gap Analysis tab."""
    if not results:
        return '<div class="empty-msg">No mapping results to display.</div>'

    compliant = sum(
        1
        for r in results
        if isinstance(r.rationale, MappingRationale)
        and r.rationale.compliance_level == ComplianceLevel.FULLY_COMPLIANT
    )
    partial = sum(
        1
        for r in results
        if isinstance(r.rationale, MappingRationale)
        and r.rationale.compliance_level == ComplianceLevel.PARTIALLY_COMPLIANT
    )
    noncompliant = len(results) - compliant - partial

    stats = f"""
    <div class="stats-bar">
      <div class="stat">
        <div class="stat-value">{len(results)}</div>
        <div class="stat-label">Total Controls</div>
      </div>
      <div class="stat">
        <div class="stat-value" style="color:var(--green)">\
{compliant}</div>
        <div class="stat-label">Compliant</div>
      </div>
      <div class="stat">
        <div class="stat-value" style="color:var(--yellow)">\
{partial}</div>
        <div class="stat-label">Partial</div>
      </div>
      <div class="stat">
        <div class="stat-value" style="color:var(--red)">\
{noncompliant}</div>
        <div class="stat-label">Non-Compliant</div>
      </div>
    </div>
    """

    filters = """
    <div class="filters">
      <button class="filter-btn active" data-filter="all">\
All</button>
      <button class="filter-btn" data-filter="compliant">\
Compliant</button>
      <button class="filter-btn" data-filter="partial">\
Partial</button>
      <button class="filter-btn" data-filter="noncompliant">\
Non-Compliant</button>
    </div>
    """

    cards = "\n".join(_render_gap_card(r) for r in results)
    return f"{stats}\n{filters}\n{cards}"


