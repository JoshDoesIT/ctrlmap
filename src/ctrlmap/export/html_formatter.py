_TEMPLATES_DIR = Path(__file__).parent / "templates"


def _load_css() -> str:
    """Load the report stylesheet from ``templates/report.css``."""
    return (_TEMPLATES_DIR / "report.css").read_text(encoding="utf-8")


def _load_js() -> str:
    """Load the report script from ``templates/report.js``."""
    return (_TEMPLATES_DIR / "report.js").read_text(encoding="utf-8")


