def _normalize_results(
    results: list[MappedResult] | None,
    results_by_framework: dict[str, list[MappedResult]] | None,
) -> dict[str, list[MappedResult]]:
    """Normalize inputs to a ``{framework: [results]}`` dict."""
    if results_by_framework is not None:
        return results_by_framework

    if results is None:
        return {}

    # Group single results list by framework
    grouped: dict[str, list[MappedResult]] = defaultdict(list)
    for r in results:
        grouped[r.control.framework].append(r)
    return dict(grouped)


# ---------------------------------------------------------------------------
# Framework pills (multi-framework only)
