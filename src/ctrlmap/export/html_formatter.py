def _render_page_overlays(
    rendered_page: object,
    chunk_controls: dict[str, list[str]],
    ctrl_details: dict[str, dict[str, str]],
) -> str:
    """Build overlay highlight divs for a single PDF page."""
    overlays = []
    for overlay in rendered_page.overlays:  # type: ignore[union-attr]
        clip = f";clip-path:{overlay.clip_path}" if overlay.clip_path else ""
        ctrls = overlay.controls or chunk_controls.get(overlay.chunk_id, [])
        if not ctrls:
            # Unmapped chunk
            overlays.append(f"""
            <div class="pdf-overlay pdf-overlay--unmapped"
                 style="left:{overlay.x_pct}%;top:{overlay.y_pct}%;\
width:{overlay.w_pct}%;height:{overlay.h_pct}%{clip}"
                 data-chunk-id="{html.escape(overlay.chunk_id)}">
            </div>
            """)
            continue

        # Determine compliance level for color
        classes = [ctrl_details.get(c, {}).get("css_class", "") for c in ctrls]
        if "noncompliant" in classes:
            color_cls = "pdf-overlay--noncompliant"
        elif "partial" in classes:
            color_cls = "pdf-overlay--partial"
        else:
            color_cls = "pdf-overlay--compliant"

        # Build popover data with all controls
        controls_data = []
        for ctrl_label in sorted(set(ctrls)):
            detail = ctrl_details.get(ctrl_label, {})
            controls_data.append({
                "id": ctrl_label,
                "title": detail.get("title", ""),
                "description": detail.get("description", ""),
                "compliance": detail.get("compliance", ""),
                "confidence": detail.get("confidence", ""),
                "rationale": detail.get("rationale", ""),
            })

        popover_json = html.escape(json.dumps(controls_data), quote=True)

        overlays.append(f"""
        <div class="pdf-overlay {color_cls} doc-reader-chunk--mapped"
             style="left:{overlay.x_pct}%;top:{overlay.y_pct}%;\
width:{overlay.w_pct}%;height:{overlay.h_pct}%{clip}"
             data-chunk-id="{html.escape(overlay.chunk_id)}"
             data-popover="{popover_json}">
        </div>
        """)

    return "".join(overlays)


def _render_text_reader(
    results: list[MappedResult],
    all_chunks: list[ParsedChunk] | None,
    chunk_controls: dict[str, list[str]],
    ctrl_details: dict[str, dict[str, str]],
) -> str:
    """Text-based document reader fallback (no PDF data available)."""
    chunk_registry: dict[str, ParsedChunk] = {}
    for result in results:
        for chunk in result.supporting_chunks:
            chunk_registry[chunk.chunk_id] = chunk

    if all_chunks:
        for chunk in all_chunks:
            if chunk.chunk_id not in chunk_registry:
                chunk_registry[chunk.chunk_id] = chunk

    if not chunk_registry:
        return '<div class="empty-msg">No documents to display.</div>'

    order_index = {c.chunk_id: i for i, c in enumerate(all_chunks)} if all_chunks else {}

    docs: dict[str, list[ParsedChunk]] = defaultdict(list)
    seen: set[str] = set()
    for cid, chunk in chunk_registry.items():
        if cid not in seen:
            docs[chunk.document_name].append(chunk)
            seen.add(cid)

    for chunks in docs.values():
        chunks.sort(key=lambda c: order_index.get(c.chunk_id, (c.page_number * 1000)))

    sections = []
    for doc_name in sorted(docs):
        chunks = docs[doc_name]
        chunk_html_parts = []
        current_page = -1

        for chunk in chunks:
            if chunk.page_number != current_page:
                current_page = chunk.page_number
                chunk_html_parts.append(
                    f'<div class="page-separator"><span>Page {current_page}</span></div>'
                )

            ctrls = chunk_controls.get(chunk.chunk_id, [])
            is_mapped = bool(ctrls)

            border_cls = "doc-reader-chunk--unmapped"
            if is_mapped:
                border_cls = "doc-reader-chunk--mapped"
                classes = [ctrl_details.get(c, {}).get("css_class", "") for c in ctrls]
                if "noncompliant" in classes:
                    border_cls += " doc-reader-border--noncompliant"
                elif "partial" in classes:
                    border_cls += " doc-reader-border--partial"
                else:
                    border_cls += " doc-reader-border--compliant"

            tags_html = ""
            if ctrls:
                tag_parts = []
                for ctrl_label in sorted(set(ctrls)):
                    detail = ctrl_details.get(ctrl_label, {})
                    popover_data = html.escape(
                        json.dumps({
                            "id": ctrl_label,
                            "title": detail.get("title", ""),
                            "compliance": detail.get("compliance", ""),
                            "confidence": detail.get("confidence", ""),
                            "explanation": detail.get("explanation", ""),
                        }),
                        quote=True,
                    )
                    tag_parts.append(
                        f'<span class="ctrl-tag" data-popover="{popover_data}">'
                        f"{html.escape(ctrl_label)}</span>"
                    )
                tags_html = f'<div class="doc-reader-tags">{"".join(tag_parts)}</div>'

            sec = html.escape(chunk.section_header or "")
            sec_html = f'<div class="doc-reader-section">{sec}</div>' if sec else ""
            txt = html.escape(chunk.raw_text.replace("\n", " ").strip())

            chunk_html_parts.append(f"""
            <div class="doc-reader-chunk {border_cls}">
              {sec_html}
              <div class="doc-reader-text">{txt}</div>
              {tags_html}
            </div>
            """)

        sections.append(f"""
        <div class="doc-reader-doc">
          <h3 class="doc-reader-title">{html.escape(doc_name)}</h3>
          {"".join(chunk_html_parts)}
        </div>
        """)

    return "\n".join(sections)


