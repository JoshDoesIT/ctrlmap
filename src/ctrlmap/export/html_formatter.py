_FW_DISPLAY_NAMES: dict[str, str] = {
    "PCI-DSS": "PCI DSS",
    "NIST-800-53": "NIST 800-53",
}


def _fw_display_name(fw_id: str) -> str:
    """Convert a framework ID to a human-readable display name."""
    return _FW_DISPLAY_NAMES.get(fw_id, fw_id.replace("-", " "))


def _render_framework_pills(
    fw_results: dict[str, list[MappedResult]],
) -> str:
    """Render framework filter pills for multi-framework reports."""
    pills = ['<button class="fw-pill active" data-fw="all">All</button>']
    for fw_name in sorted(fw_results):
        count = len(fw_results[fw_name])
        display = _fw_display_name(fw_name)
        pills.append(
            f'<button class="fw-pill" data-fw="{html.escape(fw_name)}">'
            f"{html.escape(display)} ({count})</button>"
        )
    return f'<div class="fw-pills">{"".join(pills)}</div>'


