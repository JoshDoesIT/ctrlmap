def export_html(
    results: list[MappedResult],
    path: Path,
    all_chunks: list[ParsedChunk] | None = None,
    *,
    results_by_framework: dict[str, list[MappedResult]] | None = None,
    pdf_documents: list[Any] | None = None,
) -> None:
    """Write mapping results as an interactive HTML report to disk.

    Args:
        results: List of MappedResult objects to export.
        path: Output file path.
        all_chunks: Optional list of all chunks for coverage tabs.
        results_by_framework: Optional multi-framework dict.
        pdf_documents: Optional rendered PDF data for Document Reader.
    """
    content = format_html(
        results,
        all_chunks=all_chunks,
        results_by_framework=results_by_framework,
        pdf_documents=pdf_documents,
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        mode="w",
        encoding="utf-8",
        dir=path.parent,
        suffix=".tmp",
        delete=False,
    ) as tmp:
        tmp.write(content)
        tmp_path = Path(tmp.name)
    tmp_path.rename(path)


